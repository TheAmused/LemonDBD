// frontend/scripts/generate-site-pages.mjs
//
// Discovers the site's pages from the route folders in src/app/[locale]/ and writes the registry
// the page kill switch runs on, so adding a page never means remembering a list:
//
//   src/generated/sitePages.generated.ts  -- every page id (plus the reserved ones), no imports
//   src/generated/pageNav.generated.ts    -- each page's optional `nav.ts` (sidebar label/icon/order)
//
// A folder becomes a page when it contains a page.* file. Give it a `nav.ts` (see
// src/utils/pageNav.ts) to appear in the sidebar; without one it is still switchable, just not
// listed in the navigation. Run automatically before `dev` and `build`;
// `--check` verifies the committed files are current (used by the unit tests).

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const APP_DIR = path.join(ROOT, 'src', 'app', '[locale]');
const OUT_DIR = path.join(ROOT, 'src', 'generated');

/** Routes that must never be switched off: the way back in and the pages that explain a block. */
export const RESERVED_SEGMENTS = ['admin', 'blocked', 'forbidden', 'privacy-policy', 'reset-password', 'user', 'welcome'];

const HEADER = '// GENERATED by scripts/generate-site-pages.mjs -- do not edit; run `npm run generate:pages`.\n';

function hasPageFile(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).some((entry) =>
    entry.isDirectory() ? hasPageFile(path.join(dir, entry.name)) : /^page\.(tsx|ts|jsx|js)$/.test(entry.name)
  );
}

export function discoverPages() {
  return fs
    .readdirSync(APP_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && /^[a-z0-9][a-z0-9-]*$/.test(entry.name))
    .map((entry) => entry.name)
    .filter((id) => !RESERVED_SEGMENTS.includes(id) && hasPageFile(path.join(APP_DIR, id)))
    .sort()
    .map((id) => ({ id, hasNav: fs.existsSync(path.join(APP_DIR, id, 'nav.ts')) }));
}

export function render() {
  const pages = discoverPages();
  const ids = `${HEADER}
/** Every page that can be switched off, discovered from src/app/[locale]/. */
export const SITE_PAGE_IDS = [
${pages.map((p) => `  '${p.id}',`).join('\n')}
] as const;

/** Route segments that are never switchable. */
export const RESERVED_SEGMENTS = [
${RESERVED_SEGMENTS.map((s) => `  '${s}',`).join('\n')}
] as const;
`;
  const withNav = pages.filter((p) => p.hasNav);
  const ident = (id) => `nav_${id.replace(/-/g, '_')}`;
  const nav = `${HEADER}
import type { PageNav } from '@/utils/pageNav';
${withNav.map((p) => `import { nav as ${ident(p.id)} } from '@/app/[locale]/${p.id}/nav';`).join('\n')}

/** Sidebar metadata of the pages that declared a nav.ts, keyed by page id. */
export const PAGE_NAV: Readonly<Record<string, PageNav | undefined>> = {
${withNav.map((p) => `  '${p.id}': ${ident(p.id)},`).join('\n')}
};
`;
  return {
    'sitePages.generated.ts': ids,
    'pageNav.generated.ts': nav,
  };
}

function main() {
  const check = process.argv.includes('--check');
  const files = render();
  let stale = false;
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(OUT_DIR, name);
    const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
    if (current === content) continue;
    if (check) {
      stale = true;
      console.error(`src/generated/${name} is out of date.`);
    } else {
      fs.mkdirSync(OUT_DIR, { recursive: true });
      fs.writeFileSync(file, content);
      console.log(`wrote src/generated/${name}`);
    }
  }
  if (stale) {
    console.error('A page folder was added, removed or got a nav.ts: run `npm run generate:pages` and commit the result.');
    process.exit(1);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
